def write_law_article(path: Path) -> None:
    fieldnames = [
        "law_id",
        "law_name",
        "law_level",
        "chapter",
        "section",
        "article_id",
        "article_no",
        "article_title",
        "article_text",
        "effective_date",
        "source_url",
        "remark",
    ]
    with path.open("w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        for article_id, chapter, article_no, article_text in ARTICLES:
            writer.writerow(
                {
                    "law_id": LAW_ID,
                    "law_name": LAW_NAME,
                    "law_level": LAW_LEVEL,
                    "chapter": chapter,
                    "section": "",
                    "article_id": article_id,
                    "article_no": article_no,
                    "article_title": "",
                    "article_text": article_text,
                    "effective_date": EFFECTIVE_DATE,
                    "source_url": SOURCE_URL,
                    "remark": "根据公开法规网页整理，建议人工复核标点与分款",
                }
            )


def classify_violation(name: str) -> str:
    if "饮酒" in name or "逃逸" in name or "伪造" in name or "变造" in name:
        return "严重违法"
    if "超速" in name or "规定时速" in name:
        return "超速违法"
    if "载人" in name or "载物" in name or "超限" in name:
        return "超载超限"
    if "高速公路" in name or "城市快速路" in name or "应急车道" in name:
        return "道路通行违法"
    if "校车" in name:
        return "校车相关违法"
    return "交通违法记分"


def write_violation_penalty(path: Path) -> None:
    fieldnames = [
        "violation_id",
        "violation_name",
        "violation_type",
        "related_article_id",
        "penalty_type",
        "penalty_content",
        "fine_range",
        "score_value",
        "detention",
        "license_action",
        "applicable_vehicle",
        "source_url",
        "remark",
    ]
    with path.open("w", encoding="utf-8-sig", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        index = 1
        for article_id, score, items in SCORE_ITEMS:
            for item in items:
                writer.writerow(
                    {
                        "violation_id": f"JMV{index:03d}",
                        "violation_name": item,
                        "violation_type": classify_violation(item),
                        "related_article_id": article_id,
                        "penalty_type": "记分",
                        "penalty_content": f"机动车驾驶人有该交通违法行为的，一次记{score}分",
                        "fine_range": "",
                        "score_value": score,
                        "detention": "否",
                        "license_action": "",
                        "applicable_vehicle": "机动车",
                        "source_url": SOURCE_URL,
                        "remark": f"根据{LAW_NAME}{article_id}整理，罚款金额需结合其他处罚规定补充",
                    }
                )
                index += 1


def main() -> None:
    output_dir = Path(__file__).resolve().parent / "generated"
    output_dir.mkdir(exist_ok=True)

    law_path = output_dir / "scoring_method_law_article.csv"
    violation_path = output_dir / "scoring_method_violation_penalty.csv"
    write_law_article(law_path)
    write_violation_penalty(violation_path)

    print(f"Wrote {law_path}")
    print(f"Wrote {violation_path}")
    print(f"law_article rows: {len(ARTICLES)}")
    print(f"violation_penalty rows: {sum(len(items) for _, _, items in SCORE_ITEMS)}")


if __name__ == "__main__":
    main()
